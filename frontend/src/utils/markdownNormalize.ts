/**
 * 回答正文进 Markdown 渲染器之前的兜底归一化。
 *
 * 两件事，都是"模型/资料写了人话，但 Markdown 把它当语法"：
 *
 * 1. **公式定界符**：LLM 偶发输出 LaTeX 标准写法 `\(...\)` / `\[...\]`，
 *    而 remark-math 只认 `$...$` / `$$...$$`，不归一化就原样显示成文字。
 *
 * 2. **区间符号 `~`**：中文水利资料里 `~` 只表示区间——「10~20 年一遇」
 *    「24h 降雨量 155~170mm」「雨前库水位 338.5~343m」。remark-gfm 却会把
 *    成对的两个 `~` 当成删除线定界符，于是那一段被渲染成
 *    `10<del>20 年一遇降雨（155</del>170mm）`——**正文平白被划掉一截**。
 *    实测每个含区间的回答都中招，用户看到的就是"一条横线把字划掉"。
 *
 * 转义成 `\~` 之后，CommonMark 输出字面 `~`，视觉上什么都不变；
 * 真有人写 `~~删除~~` 也只会原样显示符号，不会误删文字。
 */
export function normalizeAnswerMarkdown(text: string): string {
  if (!text) return ''
  return text
    .replace(/\\\[([\s\S]*?)\\\]/g, (_m, body) => `$$${body}$$`)
    .replace(/\\\(([\s\S]*?)\\\)/g, (_m, body) => `$${body}$`)
    .replace(/~/g, '\\~')
}
